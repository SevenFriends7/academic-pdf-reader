function stubFetch(routes) {
  // 用 RegExp 精确匹配路径，按顺序返回第一个命中的路由。
  // 【踩过的坑】早先版本用 `url.includes(pattern)`，`/items?itemType=attachment` 这个模式
  // 会把 `/items/BBBB2222` 也一起吞掉，于是拿单个条目时返回了一个数组，
  // 认领在"取父条目"那一步静默失败。桩必须能表达"这两条路径是不同端点"。
  return async (url) => {
    const u = String(url);
    for (const [pattern, resp] of routes) {
      if (new RegExp(pattern).test(u)) {
        const r = typeof resp === 'function' ? resp(u) : resp;
        return {
          ok: r.status >= 200 && r.status < 300,
          status: r.status,
          headers: { get: (k) => (r.headers || {})[k] || null },
          text: async () => r.body || ''
        };
      }
    }
    return { ok: false, status: 404, headers: { get: () => null }, text: async () => 'No endpoint found' };
  };
}

(async () => {
  // ① 没开本地 API：真机上就是这个 403 + 这段 body
  const disabled = new zc.ZoteroClient({
    fetchImpl: stubFetch([['/api/$', { status: 403, body: 'Local API is not enabled' }]])
  });
  const d1 = await disabled.detect(true);
  t('403 Local API is not enabled → reason=api-disabled，且提示里带"怎么开"', () => {
    assert.strictEqual(d1.available, false);
    assert.strictEqual(d1.reason, 'api-disabled');
    assert.ok(/设置/.test(d1.message) && /允许/.test(d1.message), d1.message);
  });

  // ② Zotero 没开：fetch 直接 ECONNREFUSED
  const down = new zc.ZoteroClient({
    fetchImpl: async () => {
      throw new Error('connect ECONNREFUSED 127.0.0.1:23119');
    }
  });
  const d2 = await down.detect(true);
  t('连不上 → reason=not-running', () => {
    assert.strictEqual(d2.reason, 'not-running');
    assert.ok(/Zotero/.test(d2.message));
  });

  // ③ 正常可用：真机的 /api/ 返回头里有 X-Zotero-Version
  const ok = new zc.ZoteroClient({
    fetchImpl: stubFetch([['/api/$', { status: 200, body: 'Nothing to see here.', headers: { 'X-Zotero-Version': '9.0.6' } }]])
  });
  const d3 = await ok.detect(true);
  t('200 → available=true 且带出 Zotero 版本', () => {
    assert.strictEqual(d3.available, true);
    assert.strictEqual(d3.version, '9.0.6');
  });

  // ④ 全文 404（附件没被索引过）
  const noIndex = new zc.ZoteroClient({
    fetchImpl: stubFetch([
      ['/api/$', { status: 200, body: '' }],
      ['/items\\?itemType=attachment', { status: 200, body: '[]' }]
    ])
  });
  const r4 = await noIndex.linkPdf('D:\\a\\b.pdf', {});
  t('库里没有匹配条目 → link=null 但 detect.available=true（不能把"没认领"说成"没连上"）', () => {
    assert.strictEqual(r4.link, null);
    assert.strictEqual(r4.detect.available, true);
  });

  // ⑤ 端到端（桩）：认领 → 取父条目 → 取全文 → 取批注
  const e2e = new zc.ZoteroClient({
    fetchImpl: stubFetch([
      ['/api/$', { status: 200, body: '' }],
      ['/items\\?itemType=attachment', {
        status: 200,
        body: JSON.stringify([
          {
            key: 'BBBB2222',
            links: {
              up: { href: 'http://localhost:23119/api/users/0/items/PAPER001' },
              enclosure: { href: 'file:///C:/Users/x/Zotero/storage/BBBB2222/Oh%20%E7%AD%89%20-%20STM.pdf', length: 4030776 }
            },
            data: { key: 'BBBB2222', itemType: 'attachment', contentType: 'application/pdf', filename: 'Oh 等 - STM.pdf' }
          }
        ])
      }],
      ['/items/PAPER001$', {
        status: 200,
        body: JSON.stringify({
          key: 'PAPER001',
          data: {
            key: 'PAPER001',
            itemType: 'conferencePaper',
            title: 'Video Object Segmentation using Space-Time Memory Networks',
            date: '2019',
            proceedingsTitle: 'ICCV',
            DOI: '10.1109/ICCV.2019.00932',
            creators: [{ lastName: 'Oh', firstName: 'Seoung Wug' }, { lastName: 'Lee' }, { lastName: 'Xu' }]
          }
        })
      }],
      ['/fulltext$', { status: 200, body: JSON.stringify({ content: 'A\fB\fC', indexedPages: 3, totalPages: 3 }) }],
      ['/children$', {
        status: 200,
        body: JSON.stringify([
          { key: 'ANNO1', data: { itemType: 'annotation', annotationType: 'highlight', annotationText: 'gy, Zhejian', annotationColor: '#ffd400', annotationPosition: '{"pageIndex":0,"rects":[[1,2,3,4]]}' } },
          { key: 'NOTE1', data: { itemType: 'note', note: '<p>x</p>' } }
        ])
      }]
    ])
  });
  const r5 = await e2e.linkPdf('D:\\论文\\Oh 等 - STM.pdf', { fileSize: 4030776, expectedPages: 3 });
  t('端到端：认领成功、元数据/全文/批注三项都到位', () => {
    assert.ok(r5.link, '应该认领成功');
    assert.strictEqual(r5.link.attachmentKey, 'BBBB2222');
    assert.strictEqual(r5.link.parentKey, 'PAPER001');
    assert.strictEqual(r5.link.matchedBy, 'basename');
    assert.strictEqual(r5.link.meta.year, '2019');
    assert.strictEqual(r5.link.meta.venue, 'ICCV');
    assert.strictEqual(r5.link.meta.creators, 'Oh et al.');
    assert.strictEqual(r5.link.meta.doi, '10.1109/ICCV.2019.00932');
    assert.strictEqual(r5.link.fullText.pages.length, 3);
    assert.strictEqual(r5.link.annotations.length, 1, 'note 子条目不是 annotation，必须被过滤掉');
    assert.strictEqual(r5.link.annotations[0].key, 'ANNO1');
  });
  t('页数不一致时 link 仍然成，但 fullText.pageCountMismatch=true（交调用方判废）', async () => {
    const mism = new zc.ZoteroClient({
      fetchImpl: stubFetch([
        ['/api/$', { status: 200, body: '' }],
        ['/items\\?itemType=attachment', {
          status: 200,
          body: JSON.stringify([
            {
              key: 'BBBB2222',
              links: { enclosure: { href: 'file:///C:/x/Oh%20%E7%AD%89%20-%20STM.pdf', length: 1 } },
              data: { key: 'BBBB2222', contentType: 'application/pdf', filename: 'x.pdf' }
            }
          ])
        }],
        ['/fulltext$', { status: 200, body: JSON.stringify({ content: 'A\fB', indexedPages: 2, totalPages: 2 }) }],
        ['/children$', { status: 200, body: '[]' }]
      ])
    });
    const r = await mism.linkPdf('D:\\x\\Oh 等 - STM.pdf', { expectedPages: 10 });
    assert.strictEqual(r.link.fullText.pageCountMismatch, true);
  });

  // ---------------------------------------------------------------------------
  console.log('\n【8】真机联调（可选）：直接打本机正在跑的 Zotero');
  // ---------------------------------------------------------------------------
  // 默认开启；设 ZOTERO_REAL_TEST=0 可跳过 —— 用来二分定位"非零退出"到底出在桩测试还是真机请求。
  // 这里刻意用 fetchImpl: null 走 Node 原生 http 路径：既覆盖了"没有全局 fetch"的兜底，
  // 也避开 undici 在 Windows 上退出时撞 libuv 断言的已知问题。
  const real = new zc.ZoteroClient({ timeoutMs: 4000, fetchImpl: null });
  if (process.env.ZOTERO_REAL_TEST === '0') {
    console.log('  ℹ️  ZOTERO_REAL_TEST=0，跳过真机联调');
    const realDetect = { available: false };
    void realDetect;
  } else {
  const realDetect = await real.detect(true);
  if (realDetect.available) {
    console.log(`  ℹ️  真机 Zotero ${realDetect.version || '?'} 可用，做一次真实认领`);
    const links = await real.listPdfAttachments(true);
    console.log(`     库里 PDF 附件 ${links.length} 个`);
    if (links.length) {
      const href = links[0].links && links[0].links.enclosure && links[0].links.enclosure.href;
      const name = zc.parseFileUrl(href).fileName;
      const link = await real.linkPdf(name, { expectedPages: undefined });
      t('真机：用真实文件名认领到条目，并拿到全文与元数据', () => {
        assert.ok(link.link, '应该认领到');
        assert.ok(link.link.fullText, '应该有全文');
        assert.ok(link.link.fullText.pages.length > 5, `页数应 >5，实际 ${link.link.fullText ? link.link.fullText.pages.length : 0}`);
        console.log(`     认领到《${link.link.meta.title}》 ${link.link.meta.summary}`);
        console.log(`     全文 ${link.link.fullText.pages.length} 页 / ${link.link.fullText.chars} 字，页数一致=${!link.link.fullText.pageCountMismatch}`);
        console.log(`     批注 ${link.link.annotations.length} 条`);
      });
    }
  } else {
    console.log(`  ℹ️  真机 Zotero 不可用（${realDetect.reason}）：${realDetect.message}`);
    console.log('     跳过硬联调；上面的桩测试已覆盖同一批代码路径。');
  }
  }
  /*
   * 用同步写输出结果，并且**不调用 process.exit()**。
   *
   * 【为什么】实测（Windows / Node 24）：真机联调那一段的输出量较大时，
   * console.log 的异步写还没落盘就 process.exit()，libuv 会在关句柄时撞
   * `Assertion failed: !(handle->flags & UV_HANDLE_CLOSING)`，退出码变成
   * 0xC0000409 —— 测试全绿、门禁却判失败（这个坑连查了三轮才定位到"输出量"这个变量）。
   * 所以：同步写 + 只设 exitCode，让 Node 自己排空后自然退出。
   */
  const report = [`\n===== 结果: ${pass} 通过 / ${fail} 失败 =====`];
  if (fail) {
    report.push('\n失败明细：');
    failures.forEach(f => report.push('  - ' + f));
  }
  report.push('');
  fs.writeSync(1, report.join('\n'));
  process.exitCode = fail ? 1 : 0;
})();
