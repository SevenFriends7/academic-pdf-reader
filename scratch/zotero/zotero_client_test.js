function mkItem(key, fileName, { size = 1000, title = 'T', contentType = 'application/pdf' } = {}) {
  return {
    key,
    links: {
      enclosure: {
        href: `file:///C:/Users/x/Zotero/storage/${key}/${encodeURIComponent(fileName)}`,
        // 真机响应的 enclosure 就带 title（= 文件名）与 length，桩必须照抄，否则测的是空气
        title: fileName,
        length: size,
        type: contentType
      }
    },
    data: { key, itemType: 'attachment', contentType, title, filename: fileName }
  };
}
const ITEMS = [
  mkItem('AAAA1111', 'Yang 等 - Associating Objects with Transformers.pdf', { size: 3428086 }),
  mkItem('BBBB2222', 'Oh 等 - 2019 - STM.pdf', { size: 4030776 }),
  mkItem('CCCC3333', 'not-a-pdf.txt', { size: 10, contentType: 'text/plain' })
];

t('完整路径一致 → matchedBy=path', () => {
  const r = zc.matchZoteroItem('C:\\Users\\x\\Zotero\\storage\\BBBB2222\\Oh 等 - 2019 - STM.pdf', undefined, ITEMS);
  assert.strictEqual(r.matchedBy, 'path');
  assert.strictEqual(r.item.key, 'BBBB2222');
});
t('只有文件名一致（用户把 PDF 拷到别处打开）→ matchedBy=basename', () => {
  const r = zc.matchZoteroItem('D:\\论文\\Oh 等 - 2019 - STM.pdf', undefined, ITEMS);
  assert.strictEqual(r.matchedBy, 'basename');
  assert.strictEqual(r.item.key, 'BBBB2222');
});
t('文件名对不上但有唯一同大小 → matchedBy=size', () => {
  const r = zc.matchZoteroItem('D:\\下载\\yang_aot_final.pdf', 3428086, ITEMS);
  assert.strictEqual(r.matchedBy, 'size');
  assert.strictEqual(r.item.key, 'AAAA1111');
});
t('完全不相关 → null（必须什么都不做，而不是猜一个）', () => {
  assert.strictEqual(zc.matchZoteroItem('D:\\无关\\other.pdf', 999, ITEMS), null);
});
t('同名两条且大小无法消歧 → null（错认比认不出更糟）', () => {
  const dup = [
    mkItem('DDDD4444', 'same.pdf', { size: 1 }),
    mkItem('EEEE5555', 'same.pdf', { size: 2 })
  ];
  assert.strictEqual(zc.matchZoteroItem('D:\\x\\same.pdf', 3, dup), null);
});
t('非 PDF 附件不参与匹配', () => {
  assert.strictEqual(zc.matchZoteroItem('D:\\x\\not-a-pdf.txt', 10, ITEMS), null);
});

